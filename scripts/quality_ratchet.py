#!/usr/bin/env python3
"""Compare lint findings with a committed baseline.

Each finding is ``relative/path<TAB>rule``. The baseline stores
``relative/path<TAB>rule<TAB>count``, sorted. A run fails when a count
increases, and when a recorded count is higher than the current one, so
fixed findings have to be dropped from the baseline instead of lingering
as allowed debt.

``update`` refuses to write a higher count unless ``--allow-increase`` is
passed. ``check-base REF`` compares the committed baseline with the same
file on another git ref and fails when this branch allows more than that
ref. A missing baseline is an error when that tool already exists on the
ref. It is a warning when the tool, or this script, is new on this branch.
``RATCHET_ALLOW_INCREASE=true`` (the ``ratchet-increase`` pull-request
label) is the reviewed way to accept a higher allowance. ``list`` prints
the ``TOOLS`` keys, and ``check-tools`` fails when a key that exists on
the base ref was renamed or removed on this branch.
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASELINES = ROOT / "quality"

HEADER = (
    "# Generated by scripts/quality_ratchet.py. Do not edit by hand.\n"
    "# Counts may only shrink. CI fails if a count rises or this file is stale.\n"
    "# Refresh with: make lint-baseline\n"
    "# update refuses a higher count unless --allow-increase is passed.\n"
)

CODE_SUFFIXES = {".py", ".ts", ".tsx", ".js", ".mjs", ".cjs", ".html"}
SKIP_DIRS = {
    ".git",
    ".venv",
    "node_modules",
    "dist",
    "coverage",
    "__pycache__",
    ".angular",
}
# The scanner's own source mentions the markers it looks for.
SUPPRESSION_SKIP = {
    "scripts/quality_ratchet.py",
    "scripts/test_quality_ratchet.py",
}

_NOQA = re.compile(
    r"#\s*(?:(?P<tool>ruff|flake8)\s*:\s*)?noqa\b(?::\s*(?P<codes>[A-Za-z0-9_,\s]+))?",
    re.IGNORECASE,
)
_TYPE_IGNORE = re.compile(r"#\s*type:\s*ignore\b(?:\[([^\]]+)\])?", re.IGNORECASE)
_MYPY_INLINE = re.compile(r"#\s*mypy:\s*([a-z-]+)", re.IGNORECASE)
_ESLINT_DISABLE = re.compile(
    r"eslint-disable(?:-next-line|-line)?\b(?:\s+([^/\n*]+))?",
    re.IGNORECASE,
)
_TS_DIRECTIVE = re.compile(r"@ts-(ignore|nocheck|expect-error)\b", re.IGNORECASE)
_PRAGMA_NO_COVER = re.compile(r"#\s*pragma:\s*no\s*cover\b", re.IGNORECASE)
_COVERAGE_IGNORE = re.compile(r"(?P<tool>istanbul|c8|v8)\s+ignore\b", re.IGNORECASE)
_ALEMBIC_VERSIONS = re.compile(r"apps/(?:[^/]+/backend|server)/alembic/versions(?:/.*)?")


def compare(current: Counter[tuple[str, str]], baseline: Counter[tuple[str, str]]) -> list[str]:
    messages: list[str] = []
    for key in sorted(set(current) | set(baseline)):
        now = current.get(key, 0)
        allowed = baseline.get(key, 0)
        path, code = key
        if now > allowed:
            messages.append(f"new {path} {code}: {now} (baseline {allowed})")
        elif now < allowed:
            messages.append(f"stale {path} {code}: {now} (baseline {allowed})")
    return messages


def increase_messages(
    current: Counter[tuple[str, str]],
    allowed: Counter[tuple[str, str]],
    *,
    word: str,
    label: str,
) -> list[str]:
    messages: list[str] = []
    for key in sorted(set(current)):
        now = current[key]
        previous = allowed.get(key, 0)
        if now > previous:
            path, code = key
            messages.append(f"{word} {path} {code}: {now} ({label} {previous})")
    return messages


def render(counts: Counter[tuple[str, str]]) -> str:
    lines = [f"{path}\t{code}\t{count}" for (path, code), count in sorted(counts.items()) if count]
    body = "\n".join(lines)
    return HEADER + (body + "\n" if body else "")


def parse_baseline(text: str, label: str) -> Counter[tuple[str, str]]:
    counts: Counter[tuple[str, str]] = Counter()
    source_moves = json.loads((ROOT / "quality/source-moves.json").read_text())
    for line_number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            raise SystemExit(f"{label}:{line_number}: expected path, code, count")
        path_text, code, count_text = parts
        counts[(source_moves.get(path_text, path_text), code)] += int(count_text)
    return counts


def load(path: Path) -> Counter[tuple[str, str]]:
    if not path.exists():
        return Counter()
    return parse_baseline(path.read_text(), str(path))


def relative(path: str) -> str:
    candidate = Path(path)
    if candidate.is_absolute():
        candidate = candidate.resolve().relative_to(ROOT)
    return candidate.as_posix()


def run(command: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(command, cwd=cwd, text=True, capture_output=True)


def ruff_findings() -> list[tuple[str, str]]:
    completed = run(
        [sys.executable, "-m", "ruff", "check", "--output-format", "json", "apps", "scripts"], ROOT
    )
    if completed.returncode not in (0, 1):
        sys.stderr.write(completed.stderr)
        raise SystemExit(completed.returncode or 1)
    payload = json.loads(completed.stdout or "[]")
    return [(relative(item["filename"]), item["code"]) for item in payload if item.get("code")]


def parse_mypy_output(stdout: str) -> list[tuple[str, str]]:
    findings: list[tuple[str, str]] = []
    for line in stdout.splitlines():
        # Notes and context lines continue an error. Only error lines count,
        # and only when mypy attached a [code].
        if ": error:" not in line or not line.endswith("]"):
            continue
        path = line.split(":", 1)[0]
        code = line.rsplit("[", 1)[-1][:-1]
        if path and code and " " not in code:
            findings.append((relative(path), code))
    return findings


def mypy_findings() -> list[tuple[str, str]]:
    completed = run(
        [sys.executable, "-m", "mypy", "--no-error-summary", "apps", "scripts"],
        ROOT,
    )
    if completed.returncode not in (0, 1):
        sys.stderr.write(completed.stdout)
        sys.stderr.write(completed.stderr)
        raise SystemExit(completed.returncode or 1)
    return parse_mypy_output(completed.stdout)


def parse_eslint_report(payload: list[dict[str, object]]) -> list[tuple[str, str]]:
    findings: list[tuple[str, str]] = []
    for result in payload:
        file_path = relative(str(result["filePath"]))
        messages = result.get("messages", [])
        if not isinstance(messages, list):
            continue
        for message in messages:
            if not isinstance(message, dict):
                continue
            rule = message.get("ruleId")
            if not rule:
                detail = message.get("message", "eslint parse error")
                raise SystemExit(f"{file_path}: {detail}")
            severity = int(message.get("severity", 1))
            # Warnings (severity 1) are debt too. severity 0 is an off rule.
            if severity >= 1:
                findings.append((file_path, str(rule)))
    return findings


def eslint_findings(prefix: str, cwd: Path, targets: list[str]) -> list[tuple[str, str]]:
    scoped = [str((cwd / target).relative_to(ROOT)) for target in targets]
    if prefix == "apps/finance/frontend" and cwd == ROOT / "apps/finance/frontend":
        scoped += ["apps/web/src", "apps/travel/frontend/src", "apps/media/frontend/src"]
    patterns = [
        pattern for target in scoped for pattern in (f"{target}/**/*.ts", f"{target}/**/*.html")
    ]
    completed = run(
        [
            str(ROOT / "node_modules/.bin/eslint"),
            "--config",
            str(ROOT / "eslint.config.js"),
            "--format",
            "json",
            "--report-unused-disable-directives",
            "--no-error-on-unmatched-pattern",
            *patterns,
        ],
        ROOT,
    )
    if completed.returncode not in (0, 1):
        sys.stderr.write(completed.stdout)
        sys.stderr.write(completed.stderr)
        raise SystemExit(completed.returncode or 1)
    try:
        payload = json.loads(completed.stdout or "[]")
    except json.JSONDecodeError as exc:
        sys.stderr.write(completed.stdout)
        sys.stderr.write(completed.stderr)
        raise SystemExit(1) from exc
    return parse_eslint_report(payload)


def _codes(raw: str | None) -> list[str]:
    if not raw:
        return []
    cleaned = raw.split("--", 1)[0]
    return [part.strip() for part in cleaned.split(",") if part.strip() and part.strip() != "--"]


def suppression_markers(line: str) -> list[str]:
    markers: list[str] = []
    noqa = _NOQA.search(line)
    if noqa:
        tool = (noqa.group("tool") or "").lower()
        prefix = f"{tool}: noqa" if tool else "noqa"
        codes = _codes(noqa.group("codes"))
        markers.extend([f"{prefix}:{code}" for code in codes] or [prefix])
    ignored = _TYPE_IGNORE.search(line)
    if ignored:
        codes = _codes(ignored.group(1))
        markers.extend([f"type: ignore[{code}]" for code in codes] or ["type: ignore"])
    mypy_inline = _MYPY_INLINE.search(line)
    if mypy_inline:
        markers.append(f"mypy: {mypy_inline.group(1).lower()}")
    disabled = _ESLINT_DISABLE.search(line)
    if disabled:
        codes = _codes(disabled.group(1))
        markers.extend(codes or ["eslint-disable"])
    directive = _TS_DIRECTIVE.search(line)
    if directive:
        markers.append(f"@ts-{directive.group(1).lower()}")
    if _PRAGMA_NO_COVER.search(line):
        markers.append("pragma: no cover")
    coverage = _COVERAGE_IGNORE.search(line)
    if coverage:
        markers.append(f"{coverage.group('tool').lower()} ignore")
    return markers


def excluded_dir(relative_dir: str) -> bool:
    """Trees the other Python gates already skip, plus Alembic revision dirs.

    A directory that is merely named ``versions`` is still scanned.
    """
    if relative_dir == "apps/site/flask" or relative_dir.startswith("apps/site/flask/"):
        return True
    return _ALEMBIC_VERSIONS.fullmatch(relative_dir) is not None


def iter_source_files() -> list[Path]:
    files: list[Path] = []
    for base in (ROOT / "apps", ROOT / "scripts", ROOT / "packages"):
        if not base.exists():
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            relative_dir = Path(dirpath).relative_to(ROOT).as_posix()
            if excluded_dir(relative_dir):
                dirnames[:] = []
                continue
            dirnames[:] = [name for name in dirnames if name not in SKIP_DIRS]
            for name in filenames:
                if Path(name).suffix in CODE_SUFFIXES:
                    files.append(Path(dirpath) / name)
    return files


def suppression_findings() -> list[tuple[str, str]]:
    findings: list[tuple[str, str]] = []
    for path in iter_source_files():
        rel = path.relative_to(ROOT).as_posix()
        if rel in SUPPRESSION_SKIP:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for line in text.splitlines():
            findings.extend((rel, marker) for marker in suppression_markers(line))
    return findings


TOOLS = {
    "ruff": (BASELINES / "ruff-baseline.txt", ruff_findings),
    "mypy": (BASELINES / "mypy-baseline.txt", mypy_findings),
    "eslint-finance": (
        BASELINES / "eslint-finance-baseline.txt",
        lambda: eslint_findings(
            "apps/finance/frontend",
            ROOT / "apps/finance/frontend",
            ["src", "e2e"],
        ),
    ),
    "eslint-site": (
        BASELINES / "eslint-site-baseline.txt",
        lambda: eslint_findings("apps/site", ROOT / "apps/site", ["src"]),
    ),
    "eslint-packages": (
        BASELINES / "eslint-packages-baseline.txt",
        lambda: eslint_findings(
            "apps/finance/frontend",
            ROOT / "packages",
            ["browser/src", "auth/src", "ui/src"],
        ),
    ),
    "suppressions": (BASELINES / "suppressions-baseline.txt", suppression_findings),
}


def git_show(ref: str, rel: str) -> str | None:
    completed = subprocess.run(
        ["git", "show", f"{ref}:{rel}"],
        cwd=ROOT,
        text=True,
        capture_output=True,
    )
    if completed.returncode == 0:
        return completed.stdout
    missing = (
        "does not exist" in completed.stderr or "exists on disk, but not in" in completed.stderr
    )
    if missing:
        return None
    sys.stderr.write(completed.stderr)
    raise SystemExit(completed.returncode or 1)


def git_baseline(ref: str, baseline_path: Path) -> str | None:
    return git_show(ref, baseline_path.relative_to(ROOT).as_posix())


def tools_in_source(source: str) -> set[str]:
    tree = ast.parse(source)
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        if not any(
            isinstance(target, ast.Name) and target.id == "TOOLS" for target in node.targets
        ):
            continue
        if not isinstance(node.value, ast.Dict):
            break
        names: set[str] = set()
        for key in node.value.keys:
            if isinstance(key, ast.Constant) and isinstance(key.value, str):
                names.add(key.value)
        return names
    return set()


def annotate(level: str, message: str) -> None:
    print(message, file=sys.stderr)
    if os.environ.get("GITHUB_ACTIONS") != "true":
        return
    escaped = message.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
    print(f"::{level}::{escaped}")


def removed_tools(base_source: str, current: set[str] | None = None) -> set[str]:
    """Keys in a base ``TOOLS`` dict that this branch no longer has.

    A rename is a removal of the old key. Callers fail on a non-empty set
    so the allowance comparison cannot be skipped by changing the name.
    """
    present = set(TOOLS) if current is None else current
    return tools_in_source(base_source) - present


def check_tools(base_ref: str) -> int:
    script = git_show(base_ref, "scripts/quality_ratchet.py")
    if script is None:
        annotate(
            "warning",
            f"no scripts/quality_ratchet.py on {base_ref}; the TOOLS rename check is skipped",
        )
        return 0
    missing = removed_tools(script)
    if missing:
        names = ", ".join(sorted(missing))
        annotate(
            "error",
            f"TOOLS on {base_ref} has keys this branch removed or renamed: {names}",
        )
        return 1
    print(f"TOOLS keys still cover {base_ref}")
    return 0


def increases_allowed(flag: bool) -> bool:
    if flag:
        return True
    return os.environ.get("RATCHET_ALLOW_INCREASE", "").strip().lower() in {"1", "true", "yes"}


def guard_update(
    current: Counter[tuple[str, str]],
    baseline: Counter[tuple[str, str]],
    *,
    allow_increase: bool,
) -> None:
    if allow_increase:
        return
    messages = increase_messages(current, baseline, word="increase", label="baseline")
    if not messages:
        return
    print("refusing to raise the baseline:", file=sys.stderr)
    for message in messages:
        print(f"  {message}", file=sys.stderr)
    print("Pass --allow-increase to record new debt on purpose.", file=sys.stderr)
    raise SystemExit(1)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Lint and suppression ratchet.")
    parser.add_argument("action", choices=["check", "update", "check-base", "list", "check-tools"])
    parser.add_argument("tool", nargs="?")
    parser.add_argument("base_ref", nargs="?")
    parser.add_argument("--allow-increase", action="store_true")
    args = parser.parse_args(argv[1:])

    if args.action == "list":
        if args.tool or args.base_ref:
            print("usage: quality_ratchet.py list", file=sys.stderr)
            return 2
        for name in sorted(TOOLS):
            print(name)
        return 0

    if args.action == "check-tools":
        if not args.tool or args.base_ref:
            print("usage: quality_ratchet.py check-tools BASE_REF", file=sys.stderr)
            return 2
        return check_tools(args.tool)

    if args.tool not in TOOLS:
        print(
            f"usage: quality_ratchet.py {args.action} TOOL"
            + (" BASE_REF" if args.action == "check-base" else ""),
            file=sys.stderr,
        )
        return 2
    baseline_path, collect = TOOLS[args.tool]

    if args.action == "check-base":
        if not args.base_ref:
            print("usage: quality_ratchet.py check-base TOOL BASE_REF", file=sys.stderr)
            return 2
        text = git_baseline(args.base_ref, baseline_path)
        if text is None:
            rel = baseline_path.relative_to(ROOT).as_posix()
            script = git_show(args.base_ref, "scripts/quality_ratchet.py")
            if script is None:
                annotate(
                    "warning",
                    f"{args.tool}: no scripts/quality_ratchet.py on {args.base_ref}; "
                    f"{rel} is a new gate and the allowance check is skipped",
                )
                return 0
            if args.tool not in tools_in_source(script):
                annotate(
                    "warning",
                    f"{args.tool}: not in TOOLS on {args.base_ref}; "
                    f"{rel} is a new gate and the allowance check is skipped",
                )
                return 0
            annotate(
                "error",
                f"{args.tool}: {rel} is missing on {args.base_ref}, but {args.tool} is already "
                "in TOOLS there. Restoring or renaming a baseline has to be explicit.",
            )
            return 1
        proposed = load(baseline_path)
        base_counts = parse_baseline(text, f"{args.base_ref}:{baseline_path.name}")
        messages = increase_messages(proposed, base_counts, word="raised", label="base")
        if messages and increases_allowed(args.allow_increase):
            annotate(
                "warning",
                f"{args.tool}: allowance rose against {args.base_ref} and "
                "RATCHET_ALLOW_INCREASE is set:\n" + "\n".join(messages),
            )
            return 0
        if messages:
            print(f"{args.tool} allowance rose against {args.base_ref}:", file=sys.stderr)
            for message in messages:
                print(f"  {message}", file=sys.stderr)
            return 1
        print(f"{args.tool}: allowance is within {args.base_ref}")
        return 0

    current = Counter(collect())
    if args.action == "update":
        guard_update(current, load(baseline_path), allow_increase=args.allow_increase)
        baseline_path.parent.mkdir(parents=True, exist_ok=True)
        baseline_path.write_text(render(current))
        print(f"wrote {baseline_path.relative_to(ROOT)} ({sum(current.values())} findings)")
        return 0

    messages = compare(current, load(baseline_path))
    if messages:
        print(f"{args.tool} baseline mismatch ({len(messages)}):", file=sys.stderr)
        for message in messages:
            print(f"  {message}", file=sys.stderr)
        print("Refresh a shrink with: make lint-baseline", file=sys.stderr)
        return 1
    print(f"{args.tool}: {sum(current.values())} findings match the baseline")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
