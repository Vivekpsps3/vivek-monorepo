#!/usr/bin/env python3
"""Compare lint findings with a committed baseline.

Each finding is ``relative/path<TAB>RULE``. The baseline stores
``relative/path<TAB>RULE<TAB>count``, sorted. A run fails when a count
increases, and when a recorded count is higher than the current one, so
fixed findings have to be dropped from the baseline instead of lingering
as allowed debt.
"""

from __future__ import annotations

import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASELINES = ROOT / "quality"

HEADER = (
    "# Generated by scripts/quality_ratchet.py. Do not edit by hand.\n"
    "# Counts may only shrink. CI fails if a count rises or this file is stale.\n"
    "# Refresh with: make lint-baseline\n"
)


def compare(current: Counter[tuple[str, str]], baseline: Counter[tuple[str, str]]) -> list[str]:
    messages: list[str] = []
    for key in sorted(set(current) | set(baseline)):
        now = current.get(key, 0)
        allowed = baseline.get(key, 0)
        path, code = key
        if now > allowed:
            messages.append(f"new {path} {code}: {now} (baseline {allowed})")
        elif now < allowed:
            messages.append(f"stale {path} {code}: {now} (baseline {allowed})")
    return messages


def render(counts: Counter[tuple[str, str]]) -> str:
    lines = [f"{path}\t{code}\t{count}" for (path, code), count in sorted(counts.items()) if count]
    body = "\n".join(lines)
    return HEADER + (body + "\n" if body else "")


def load(path: Path) -> Counter[tuple[str, str]]:
    counts: Counter[tuple[str, str]] = Counter()
    if not path.exists():
        return counts
    for line_number, raw in enumerate(path.read_text().splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            raise SystemExit(f"{path}:{line_number}: expected path, code, count")
        path_text, code, count_text = parts
        counts[(path_text, code)] = int(count_text)
    return counts


def relative(path: str) -> str:
    candidate = Path(path)
    if candidate.is_absolute():
        candidate = candidate.resolve().relative_to(ROOT)
    return candidate.as_posix()


def run(command: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(command, cwd=cwd, text=True, capture_output=True)


def ruff_findings() -> list[tuple[str, str]]:
    completed = run(
        [sys.executable, "-m", "ruff", "check", "--output-format", "json", "apps", "scripts"], ROOT
    )
    if completed.returncode not in (0, 1):
        sys.stderr.write(completed.stderr)
        raise SystemExit(completed.returncode or 1)
    payload = json.loads(completed.stdout or "[]")
    return [(relative(item["filename"]), item["code"]) for item in payload if item.get("code")]


def mypy_findings() -> list[tuple[str, str]]:
    completed = run(
        [sys.executable, "-m", "mypy", "--no-error-summary", "apps", "scripts"],
        ROOT,
    )
    if completed.returncode not in (0, 1):
        sys.stderr.write(completed.stdout)
        sys.stderr.write(completed.stderr)
        raise SystemExit(completed.returncode or 1)
    findings: list[tuple[str, str]] = []
    for line in completed.stdout.splitlines():
        # path:line: error: message [code]
        if ": error:" not in line or not line.endswith("]"):
            continue
        path = line.split(":", 1)[0]
        code = line.rsplit("[", 1)[-1][:-1]
        if path and code and " " not in code:
            findings.append((relative(path), code))
    return findings


def eslint_findings(prefix: str, cwd: Path, targets: list[str]) -> list[tuple[str, str]]:
    completed = run(
        [
            "npm",
            "exec",
            "--prefix",
            str(ROOT / prefix),
            "--",
            "eslint",
            "--format",
            "json",
            *targets,
        ],
        cwd,
    )
    if completed.returncode not in (0, 1):
        sys.stderr.write(completed.stdout)
        sys.stderr.write(completed.stderr)
        raise SystemExit(completed.returncode or 1)
    try:
        payload = json.loads(completed.stdout or "[]")
    except json.JSONDecodeError as exc:
        sys.stderr.write(completed.stdout)
        sys.stderr.write(completed.stderr)
        raise SystemExit(1) from exc
    findings: list[tuple[str, str]] = []
    for result in payload:
        file_path = relative(result["filePath"])
        for message in result.get("messages", []):
            rule = message.get("ruleId")
            if rule is None:
                sys.stderr.write(f"{file_path}: {message.get('message', 'eslint parse error')}\n")
                raise SystemExit(1)
            if message.get("severity", 2) >= 2:
                findings.append((file_path, rule))
    return findings


TOOLS = {
    "ruff": (BASELINES / "ruff-baseline.txt", ruff_findings),
    "mypy": (BASELINES / "mypy-baseline.txt", mypy_findings),
    "eslint-finance": (
        BASELINES / "eslint-finance-baseline.txt",
        lambda: eslint_findings(
            "apps/finance/frontend",
            ROOT / "apps/finance/frontend",
            ["src", "e2e"],
        ),
    ),
    "eslint-site": (
        BASELINES / "eslint-site-baseline.txt",
        lambda: eslint_findings("apps/site", ROOT / "apps/site", ["src"]),
    ),
    "eslint-packages": (
        BASELINES / "eslint-packages-baseline.txt",
        lambda: eslint_findings(
            "apps/finance/frontend",
            ROOT / "packages",
            ["browser/src", "auth/src", "ui/src"],
        ),
    ),
}


def main(argv: list[str]) -> int:
    if len(argv) != 3 or argv[1] not in {"check", "update"} or argv[2] not in TOOLS:
        names = ", ".join(TOOLS)
        print(f"usage: quality_ratchet.py check|update {{{names}}}", file=sys.stderr)
        return 2
    action, tool = argv[1], argv[2]
    baseline_path, collect = TOOLS[tool]
    current = Counter(collect())
    if action == "update":
        baseline_path.parent.mkdir(parents=True, exist_ok=True)
        baseline_path.write_text(render(current))
        print(f"wrote {baseline_path.relative_to(ROOT)} ({sum(current.values())} findings)")
        return 0
    baseline = load(baseline_path)
    messages = compare(current, baseline)
    if messages:
        print(f"{tool} baseline mismatch ({len(messages)}):", file=sys.stderr)
        for message in messages:
            print(f"  {message}", file=sys.stderr)
        print("Refresh a shrink with: make lint-baseline", file=sys.stderr)
        return 1
    print(f"{tool}: {sum(current.values())} findings match the baseline")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
